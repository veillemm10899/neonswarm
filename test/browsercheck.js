/* Browser-only check for NEONSWARM. Loaded into a copy of the REAL index.html
   (see `_browsercheck.html`, generated by test/make-browsercheck.js) so the
   actual DOM, the actual boot path and the actual rAF loop are exercised.

   The node suites (smoke/content) stub the DOM with a Proxy that answers
   every getElementById, so they can never catch a missing element, a Canvas2D
   draw crash, or an error thrown inside the real game loop. This file can.

   Writes results into #browsercheck-log and sets document.title to
   CHECK-PASS n/n or CHECK-FAIL, so `chromium --dump-dom` can read them. */
(function () {
  var lines = [], pass = 0, fail = 0;
  var errors = [];
  window.addEventListener('error', function (e) { errors.push(String(e.message)); });

  function render() {
    var el = document.getElementById('browsercheck-log');
    if (!el) { document.title = 'CHECK-NOOUT'; return; }
    el.textContent = lines.join('\n') +
      '\n\nRESULT ' + pass + ' passed, ' + fail + ' failed';
    el.className = fail ? 'bad' : 'ok';
    document.title = fail ? 'CHECK-FAIL' : 'CHECK-PASS ' + pass + '/' + (pass + fail);
  }
  function ok(msg) { lines.push('PASS  ' + msg); pass++; render(); }
  function bad(msg) { lines.push('FAIL  ' + msg); fail++; render(); }
  function assert(cond, msg) { (cond ? ok : bad)(msg); }
  function sleep(ms) { return new Promise(function (r) { setTimeout(r, ms); }); }

  async function run() {
    await sleep(600); /* let main.js boot */

    try {
      assert(!!(window.NS && NS.Game && NS.Weapons), 'modules loaded');
      var nW = Object.keys(NS.Weapons.DEFS).length;
      var nP = Object.keys(NS.Weapons.PASSIVES).length;
      assert(nW === 30, '30 weapons registered (' + nW + ')');
      assert(nP === 46, '46 passives registered (' + nP + ')');

      /* start a real run through the real newRun, which touches the DOM */
      NS.Game.newRun(false);
      await sleep(300);
      assert(NS.Game.mode === 'play', 'real newRun() started, mode=' + NS.Game.mode);
      assert(document.getElementById('hud').style.display === 'block', '#hud shown by newRun');

      /* global passives must move every weapon */
      var s = NS.Game.state;
      var cdBefore = s.cdMult;
      NS.Weapons.applyChoice({ type: 'passive', id: 'haste', lvl: 1 });
      NS.Weapons.applyChoice({ type: 'passive', id: 'pierce', lvl: 1 });
      NS.Weapons.applyChoice({ type: 'passive', id: 'area', lvl: 1 });
      assert(s.cdMult < cdBefore, 'attack speed hits all weapons: cdMult ' +
        cdBefore.toFixed(3) + ' -> ' + s.cdMult.toFixed(3));
      assert(s.mods.pierce === 1, 'LANCE PROTOCOL pierce=' + s.mods.pierce);
      assert(s.mods.size > 1, 'BLAST SHAPE size=' + s.mods.size.toFixed(2));

      /* let the REAL rAF loop run with real input and real rendering */
      var p = NS.Game.player;
      p.maxHp = 100000; p.hp = 100000; p.armor = 9999;
      /* 1) the real boot path must have installed a render loop and drawn at
            least once. NOTE: under --virtual-time-budget rAF fires but the
            clock does not advance, so the game clock cannot be measured here —
            check for pixels instead, then drive updates explicitly below. */
      await sleep(1200);
      var cv0 = document.getElementById('game');
      var cx0 = cv0.getContext('2d');
      var px0 = cx0.getImageData(0, 0, cv0.width, cv0.height).data;
      var lit0 = 0, tot0 = 0;
      for (var j0 = 0; j0 < px0.length; j0 += 4 * 53) { tot0++; if (px0[j0] + px0[j0 + 1] + px0[j0 + 2] > 45) lit0++; }
      assert(lit0 > tot0 * 0.005, 'real boot loop drew before any input (' +
        Math.round(100 * lit0 / tot0) + '% lit)');

      /* 2) drive the loop deterministically: virtual-time budget makes
            setTimeout jump instantly while rAF gets only a few callbacks, so
            a wall-clock wait is useless here. Real DOM + real canvas, but an
            explicit number of update steps. */
      var k0 = s.kills;
      NS.Input.joy.x = 1; NS.Input.joy.y = 0.4; NS.Input.joy.active = true;
      for (var f = 0; f < 900; f++) {          /* 30s of game time at 30fps */
        NS.Game.update(1 / 30);
        NS.Input.endFrame();
        if (NS.Game.mode === 'draft' || NS.Upgrades.open) {
          var ch = NS.Upgrades.choices;
          if (ch && ch.length) NS.Upgrades.pick(0);
        }
      }
      lines.push('      (diag: t=' + s.time.toFixed(1) + 's enemies=' + NS.Enemies.list.length +
                 ' bullets=' + NS.Game.bullets.length + ' kills=' + s.kills + ' lv=' + p.level + ')');
      assert(NS.Enemies.list.length > 0, 'the spawner produced enemies (' + NS.Enemies.list.length + ')');
      assert(s.kills > k0, 'weapons killed things: +' + (s.kills - k0) + ' over 30s of game time');
      assert(NS.Game.bullets.length > 0, 'projectiles live: ' + NS.Game.bullets.length);
      assert(NS.Game.mode === 'play', 'still playing after 30s of game time');

      /* the canvas must actually have pixels on it */
      var c = document.getElementById('game');
      var ctx = c.getContext('2d');
      var d = ctx.getImageData(0, 0, c.width, c.height).data;
      var lit = 0, total = 0;
      for (var i = 0; i < d.length; i += 4 * 53) { total++; if (d[i] + d[i + 1] + d[i + 2] > 45) lit++; }
      var pct = Math.round(100 * lit / total);
      assert(pct > 1, 'canvas painted ' + c.width + 'x' + c.height + ', lit ' + pct + '% of samples');

      /* every weapon's drawExtra must survive the real Canvas2D */
      var drawFails = [];
      for (var id in NS.Weapons.DEFS) {
        var def = NS.Weapons.DEFS[id];
        if (!def.drawExtra) continue;
        s.weapons[id] = { lvl: NS.Weapons.DEFS[id].maxLvl, cd: 0 };
        var wctx = { weapons: s.weapons, player: p, dt: 1 / 60, cam: { x: 0, y: 0 },
                     ctx: ctx, wid: id, bctx: p, time: s.time };
        try { def.fire(wctx, NS.Weapons.DEFS[id].maxLvl); def.drawExtra(wctx); }
        catch (e) { drawFails.push(id + ': ' + e.message); }
      }
      assert(drawFails.length === 0, 'every weapon fires + draws on real Canvas2D' +
        (drawFails.length ? ' -- ' + drawFails.join(' | ') : ''));

      assert(errors.length === 0, 'no window errors' + (errors.length ? ': ' + errors.join(' | ') : ''));
    } catch (e) {
      bad('EXCEPTION: ' + e.message);
      if (e.stack) lines.push('        ' + e.stack.split('\n').slice(1, 3).join('\n        '));
    }
    render();
  }

  window.addEventListener('load', function () { setTimeout(run, 400); });
})();
